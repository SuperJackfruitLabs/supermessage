def code_only(source: str) -> str:
    """Strip comments, so a guard inspects code rather than prose.

    These emitters document the traps they avoid — the Swift says
    "Font.system(size:) does not scale", the Kotlin says "a hardcoded .sp
    would ignore it". A naive `assertNotIn` then fires on the explanation
    and not on any real defect, which is how a guard ends up being deleted
    for crying wolf.
    """
    out, in_block = [], False
    for line in source.splitlines():
        stripped = line.strip()
        if in_block:
            if "*/" in stripped:
                in_block = False
            continue
        if stripped.startswith("/*"):
            in_block = "*/" not in stripped
            continue
        if stripped.startswith("//") or stripped.startswith("*"):
            continue
        out.append(line)
    return "\n".join(out)



class AppCssTests(unittest.TestCase):
    def setUp(self):
        self.css = emit_app_css(load(SOURCE))
        self.root = self.css.split("@layer theme")[0]

    def test_it_says_it_is_generated(self):
        self.assertIn("Generated by scripts/generate-tokens.py", self.css)
        self.assertIn("do not edit", self.css.lower())

    def test_light_is_the_bare_root_and_defines_every_role(self):
        for role in ROLES:
            with self.subTest(role=role):
                self.assertIn(f"--color-{role}:", self.root)

    def test_no_colour_is_defined_only_inside_a_media_query(self):
        """A colour whose only definition is in the dark block leaves the
        light theme with nothing. This is the rule app.css already follows
        and the one a generator can enforce for free."""
        declared_anywhere = set(re.findall(r"--color-([a-z-]+):", self.css))
        declared_in_root = set(re.findall(r"--color-([a-z-]+):", self.root))
        self.assertEqual(declared_anywhere - declared_in_root, set())

    def test_dark_is_a_prefers_color_scheme_block(self):
        self.assertIn("@media (prefers-color-scheme: dark)", self.css)

    def test_paper_is_an_attribute_selector_not_the_default(self):
        self.assertIn('[data-appearance="paper"]', self.css)
        self.assertNotIn("#faf8f3", self.root)

    def test_every_appearances_values_actually_reach_the_output(self):
        tokens = load(SOURCE)
        for name, appearance in tokens.appearances.items():
            with self.subTest(appearance=name):
                self.assertIn(appearance.colors["surface"], self.css)
                self.assertIn(appearance.colors["signal"], self.css)

    def test_rationale_reaches_the_output(self):
        self.assertIn("2.92", self.css)

    def test_it_matches_the_golden_file(self):
        self.assertEqual(self.css, (GOLDEN / "app-tokens.css").read_text())



