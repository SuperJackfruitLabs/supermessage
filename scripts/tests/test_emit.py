class KotlinTests(unittest.TestCase):
    def setUp(self):
        from scripts.tokens.emit_kotlin import emit_kotlin

        self.kt = emit_kotlin(load(SOURCE))

    def test_it_says_it_is_generated(self):
        self.assertIn("Generated by scripts/generate-tokens.py", self.kt)

    def test_all_three_palettes_exist(self):
        for name in ("light", "dark", "paper"):
            with self.subTest(name=name):
                self.assertIn(f"val {name} = SupermessageColorRoles(", self.kt)

    def test_colours_are_argb_longs(self):
        self.assertIn("Color(0xFFFDFCFF)", self.kt)

    def test_the_scrim_carries_its_alpha_in_the_argb(self):
        """A scrim emitted at 0xFF is opaque and hides the roster instead of
        veiling it, which is the whole failure this token exists to avoid.

        0.45 -> 0x73. 0.70 -> 0xB2, not 0xB3: 0.70 * 255 is exactly 178.5
        and Python rounds half to even. Either half is defensible (178/255
        is 0.698, 179/255 is 0.702) and the difference is invisible — but
        the value is pinned so a change to the rounding shows up as a
        failing test rather than as a silently different wash.
        """
        self.assertIn("Color(0x73221C38)", self.kt)
        self.assertIn("Color(0xB2151129)", self.kt)

    def test_no_sp_sizes_leak_in(self):
        # Android's equivalent of the Dynamic Type trap: a hardcoded sp
        # value ignores the reader's font-size setting.
        self.assertNotIn(".sp", code_only(self.kt))

    def test_role_names_match_the_swift_emitter(self):
        """The clearLayers/clearFullLayers bug, pinned.

        Two emitters naming the same role differently is not a compile
        error on either platform — it just means the two apps disagree
        about what a token is called, which is where this whole project
        started.
        """
        from scripts.tokens.emit_swift import emit_swift

        swift = emit_swift(load(SOURCE))
        for role in ROLES:
            head, *rest = role.split("-")
            camel = head + "".join(p.capitalize() for p in rest)
            with self.subTest(role=role):
                self.assertIn(camel, self.kt)
                self.assertIn(camel, swift)

    def test_it_matches_the_golden_file(self):
        self.assertEqual(
            self.kt, (GOLDEN / "GeneratedThemeTokens.kt").read_text()
        )

